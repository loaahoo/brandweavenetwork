import type { Channel, ChannelCategory, CompensationModel } from "../types";

type Seed = {
  id: string;
  brandId: string;
  name: string;
  category: ChannelCategory;
  description: string;
  reach: number;
  reachUnit: string;
  geography?: string[];
  segment: string;
  placements: string[];
  types: CompensationModel[];
  pref: string;
  min: string;
  restrictions?: string[];
  approval?: boolean;
  status?: Channel["status"];
  desired?: string[];
};

const ch = (s: Seed): Channel => ({
  id: s.id,
  brandId: s.brandId,
  name: s.name,
  category: s.category,
  description: s.description,
  monthlyReach: s.reach,
  reachLabel: `${new Intl.NumberFormat("en-US", { notation: "compact", maximumFractionDigits: 1 }).format(s.reach)} ${s.reachUnit}`,
  geography: s.geography ?? ["United States"],
  segment: s.segment,
  placements: s.placements,
  partnershipTypes: s.types,
  compensationPreference: s.pref,
  minimumCommitment: s.min,
  restrictions: s.restrictions ?? [],
  approvalRequired: s.approval ?? true,
  status: s.status ?? "Available",
  desiredPartnerCategories: s.desired ?? [],
});

